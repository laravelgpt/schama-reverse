import JSZip from 'jszip';
import { CanonicalSchema, GeneratedFile } from '../../types/schema';
import { generateLaravelFiles } from './laravelGenerator';
import { generateNodeFiles } from './nodeGenerator';
import { generateDbml } from './dbmlGenerator';
import { generateMermaid } from './mermaidGenerator';
import { generateSqlDump, generateHtmlReport } from './reportGenerators';

export async function createDownloadPackage(schema: CanonicalSchema): Promise<{
  blob: Blob;
  files: GeneratedFile[];
  filename: string;
}> {
  const zip = new JSZip();
  const allFiles: GeneratedFile[] = [];

  // 1. Laravel Files (Migrations, Models with #[] attributes, Factories, Seeders)
  const laravelFiles = generateLaravelFiles(schema);
  allFiles.push(...laravelFiles);

  // 2. Node Files
  const nodeFiles = generateNodeFiles(schema);
  allFiles.push(...nodeFiles);

  // 3. DBML
  const dbmlFile = generateDbml(schema);
  allFiles.push(dbmlFile);

  // 4. Mermaid
  const mermaidFile = generateMermaid(schema);
  allFiles.push(mermaidFile);

  // 5. Consolidated SQL Script
  const sqlDump = generateSqlDump(schema);
  allFiles.push({
    path: `schema/schema-${schema.database.engine}.sql`,
    filename: `schema-${schema.database.engine}.sql`,
    category: 'reports',
    content: sqlDump,
    language: 'sql'
  });

  // 6. Standalone Interactive HTML Data Dictionary
  const htmlReport = generateHtmlReport(schema);
  allFiles.push({
    path: `schema/data-dictionary.html`,
    filename: `data-dictionary.html`,
    category: 'reports',
    content: htmlReport,
    language: 'html'
  });

  // 7. Manifest (Section 126 of spec)
  const manifest = {
    generator: 'SchemaForge',
    generator_version: '1.0.0',
    schema_version: schema.schemaVersion,
    generated_at: new Date().toISOString(),
    source_engine: schema.database.engine,
    table_count: schema.tables.length,
    relationship_count: schema.relationships.length,
    warnings_count: schema.warnings.length,
    health_score: schema.health.overallScore
  };

  const manifestFile: GeneratedFile = {
    path: 'schemaforge-manifest.json',
    filename: 'schemaforge-manifest.json',
    category: 'manifest',
    content: JSON.stringify(manifest, null, 2),
    language: 'json'
  };
  allFiles.push(manifestFile);

  // 8. README.md
  const readmeContent = `# SchemaForge Generated Artifacts

Generated by **SchemaForge** - Universal Database Reverse Engineering, Schema Analyzer & Code Generator.

## Architecture Summary
- **Source Database Engine**: \`${schema.database.engine.toUpperCase()}\`
- **Tables Analyzed**: ${schema.tables.length}
- **Relationships Detected**: ${schema.relationships.length}
- **Schema Health Score**: ${schema.health.overallScore} / 100
- **Generated At**: ${new Date().toUTCString()}

---

## Included Artifacts

### 1. Laravel 13 (PHP 8.5+) with Modern ORM PHP 8 Attributes
- **Eloquent Models** in \`app/Models/\`:
  - Uses modern **PHP 8 \`#[]\` Attributes**:
    - \`#[Table(name: '...', key: '...', incrementing: false)]\` for declarative table and key bindings
    - \`#[UseFactory(ModelFactory::class)]\` for direct model-factory association
    - \`#[WithoutTimestamps]\` when tables omit timestamp tracking
    - \`#[Scope]\` on local query scopes (e.g. \`active()\`, \`latestFirst()\`)
  - Modern method-based \`casts(): array\` for strict data type conversions
  - Mass-assignment \`protected $fillable\` typed with \`@var list<string>\`
  - Fully typed relationships (\`BelongsTo\`, \`HasMany\`, \`BelongsToMany\`)
- **Model Factories** in \`database/factories/\`:
  - Declarative factory definitions using native Laravel \`fake()\` helpers
- **Migrations** in \`database/migrations/\`:
  - Ordered topologically according to foreign-key dependencies (with safe 2-phase circular resolution).
- **Database Seeders** in \`database/seeders/\`:
  - Bulk insert arrays populated from detected \`INSERT\` rows or records.

### 2. Node.js & JSON
- **Canonical Schema** in \`node/schema.json\`
- **Table Definitions** in \`node/tables/*.json\`
- **Relationships Graph** in \`node/relationships.json\`

### 3. Visual, DDL & Modeling Formats
- **Consolidated SQL DDL** in \`schema/schema-${schema.database.engine}.sql\`
- **Interactive HTML Data Dictionary** in \`schema/data-dictionary.html\`
- **DBML** in \`schema/schema.dbml\` (compatible with dbdocs.io and dbdiagram.io)
- **Mermaid** in \`schema/erd.mermaid\` (renderable in GitHub markdown or Mermaid live editor)

---

## Installation in Laravel 13 Project
1. Copy files from \`database/migrations/\` into your Laravel \`database/migrations/\` directory.
2. Copy files from \`app/Models/\` into your Laravel \`app/Models/\` directory.
3. Copy files from \`database/factories/\` into your Laravel \`database/factories/\` directory.
4. Copy seeders from \`database/seeders/\` into \`database/seeders/\`.
5. Run \`php artisan migrate\` and \`php artisan db:seed\`.
`;

  const readmeFile: GeneratedFile = {
    path: 'README.md',
    filename: 'README.md',
    category: 'docs',
    content: readmeContent,
    language: 'markdown'
  };
  allFiles.push(readmeFile);

  // Add all files into zip
  for (const file of allFiles) {
    zip.file(file.path, file.content);
  }

  const blob = await zip.generateAsync({ type: 'blob' });
  const filename = `schemaforge-${schema.database.engine}-project.zip`;

  return { blob, files: allFiles, filename };
}

export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
